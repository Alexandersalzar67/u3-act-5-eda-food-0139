import pandas as pd
import matplotlib.pyplot as plt
df_food_india = pd.read_csv('indian_food.csv')
print("DATOS LEIDOS DESDE CSV,INDIAN FOOD 0139")
print(df_food_india)
print("\n--- Mostrar nombre comida + ingredientes, comida India 0139---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- Tiempo de cocinado mostrar 10 registros con head 0139 ---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n--- Grafica comida (X) Tiempo de cocinado (y)----")
print("\n--- Grafica comida (x) texto a 20 grados ---")
nombre_y_hora.plot.bar(x='name', y='cook_time', rot=30)
plt.title('comida tipica de infia Alexander Salazar 0139')
plt.xlabel('Nombre platillo')
plt.ylabel('Tiempo de cocinado') 
plt.show()
plt.title('grafica varias columnas Alexander Salazar 0139')
nombre_y_hora = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y_hora.plot.bar(x='name', rot=30)
plt.title('grafica de 2 columnas 0139')
plt.xlabel('Nombre platillo')
plt.ylabel('Tiempo de cocinado prep y comida') 
plt.show()
print("\ngraficas apiladas una tras otra verticalmente 0139")
nombre_y_hora.plot.bar(x='name', stacked=True)
plt.title('grafica apiladas 0139')
plt.xlabel('Nombre platillo')
plt.ylabel('Tiempo de cocinado prep y comida') 
plt.show()